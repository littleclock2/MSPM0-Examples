uint16_t ADS1118_get(uint8_t MUX,uint8_t PGA){
	uint16_t command = 0b1000000011101010 + (MUX << 12) + (PGA << 9);//这是ADS1118的命令，详细请看ADS1118的datasheet
	int16_t data;
	
	/*
	与ADS1118对应的SPI设置,总之就是一大堆宏定义
	做出的变化：
	1、片选从OLED切换到了ADS1118的片选
	2、8bit一帧变成了16bit一帧
	3、相位极性变成第二个跳变沿读取
	*/
	static DL_SPI_Config gSPI_0_config = {//这里的配置是和ADS1118的配置相同的
    .mode        = DL_SPI_MODE_CONTROLLER,//控制器模式
    .frameFormat = DL_SPI_FRAME_FORMAT_MOTO4_POL0_PHA1, //4线模式，极性为0，相位为1
    .parity      = DL_SPI_PARITY_NONE,//无校验
    .dataSize    = DL_SPI_DATA_SIZE_16,//16位数据
    .bitOrder    = DL_SPI_BIT_ORDER_MSB_FIRST, //高位在前
    .chipSelectPin = DL_SPI_CHIP_SELECT_1,//片选1
	};
	/*时钟配置*/
	static const DL_SPI_ClockConfig gSPI_0_clockConfig = {//这里的配置是和ADS1118的配置相同的
    .clockSel    = DL_SPI_CLOCK_BUSCLK,//时钟源为总线时钟
    .divideRatio = DL_SPI_CLOCK_DIVIDE_RATIO_1//分频为1
	};
	/*以下操作用来重置spi寄存器，然后就可以切换到和ADS1118相同配置的spi设置*/
	DL_SPI_reset(SPI_0_INST); //reset之后才能修改配置
	DL_SPI_enablePower(SPI_0_INST);//先上电 再修改
	DL_SPI_setClockConfig(SPI_0_INST, (DL_SPI_ClockConfig *) &gSPI_0_clockConfig); //修改spi时钟配置
	DL_SPI_init(SPI_0_INST, (DL_SPI_Config *) &gSPI_0_config);//修改spi基础设置
	DL_SPI_setBitRateSerialClockDivider(SPI_0_INST, 1);//设置1分频
	DL_SPI_setFIFOThreshold(SPI_0_INST, DL_SPI_RX_FIFO_LEVEL_1_2_FULL, DL_SPI_TX_FIFO_LEVEL_1_2_EMPTY);//设置FIFO
	DL_SPI_enable(SPI_0_INST);//使能
	
	/*发送数据并接受*/
	DL_SPI_transmitDataBlocking16(SPI_0_INST,command);//发送数据
	data = DL_SPI_receiveDataBlocking16(SPI_0_INST);//接受数据
	
	
	/*将spi恢复到OLED的显示设置上*/
	DL_SPI_reset(SPI_0_INST);
	DL_SPI_enablePower(SPI_0_INST);
	SYSCFG_DL_SPI_0_init();//OLED的spi初始化
	
	return data;//这里的data没有处理，注意，4.096量程下，最大值是2^15,用data/(2^15)*4.096就可以得到电压值，当然，需要标定，这肯定不准
}


